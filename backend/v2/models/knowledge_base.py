from datetime import datetime
from uuid import UUID

from sqlalchemy import CheckConstraint, Computed, DateTime, ForeignKey, Index, Integer, String, Text, Uuid, func, text
from sqlalchemy.orm import Mapped, mapped_column

from backend.v2.db.base import Base


class KnowledgeBase(Base):
    __tablename__ = "knowledge_bases"
    __table_args__ = (
        CheckConstraint("visibility IN ('private', 'public')", name="visibility"),
        CheckConstraint(
            "(visibility = 'private' AND owner_id IS NOT NULL) OR "
            "(visibility = 'public' AND owner_id IS NULL)", name="ownership",
        ),
        CheckConstraint("length(name_key) > 0", name="name_not_blank"),
        CheckConstraint("length(description) <= 4000", name="description_length"),
        CheckConstraint("index_version >= 0", name="index_version"),
        Index("ix_knowledge_bases_owner_id", "owner_id"),
        Index("ix_knowledge_bases_visibility", "visibility", postgresql_where=text("deleted_at IS NULL")),
        Index(
            "uq_knowledge_bases_private_name", "owner_id", "name_key", unique=True,
            postgresql_where=text("visibility = 'private' AND deleted_at IS NULL"),
        ),
        Index(
            "uq_knowledge_bases_public_name", "name_key", unique=True,
            postgresql_where=text("visibility = 'public' AND deleted_at IS NULL"),
        ),
    )

    id: Mapped[UUID] = mapped_column(Uuid, primary_key=True, server_default=text("gen_random_uuid()"))
    owner_id: Mapped[UUID | None] = mapped_column(ForeignKey("users.id", ondelete="RESTRICT"))
    name: Mapped[str] = mapped_column(String(120))
    # Generated by PostgreSQL, so even direct SQL cannot forge a different unique key.
    name_key: Mapped[str] = mapped_column(
        Text, Computed("lower(btrim(regexp_replace(normalize(name, NFKC), '[[:space:]]+', ' ', 'g')))", persisted=True),
    )
    description: Mapped[str] = mapped_column(Text, server_default="")
    visibility: Mapped[str] = mapped_column(String(7), server_default="private")
    index_version: Mapped[int] = mapped_column(Integer, server_default=text("0"))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), onupdate=func.now())
    deleted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
